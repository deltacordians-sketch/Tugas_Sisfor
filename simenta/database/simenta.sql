CREATE DATABASE IF NOT EXISTS simenta CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE simenta;
SET FOREIGN_KEY_CHECKS=0;
DROP VIEW IF EXISTS v_terakhir;
DROP TABLE IF EXISTS konseling, skrining, mahasiswa, users;
SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE users (id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, nama VARCHAR(100) NOT NULL) ENGINE=InnoDB;
CREATE TABLE mahasiswa (id INT AUTO_INCREMENT PRIMARY KEY, nim VARCHAR(20) NOT NULL UNIQUE, nama VARCHAR(100) NOT NULL, jenis_kelamin ENUM('Laki-laki','Perempuan') NOT NULL, fakultas VARCHAR(60) NOT NULL, prodi VARCHAR(80) NOT NULL, semester TINYINT NOT NULL, ipk DECIMAL(3,2) NOT NULL DEFAULT 0) ENGINE=InnoDB;
CREATE TABLE skrining (id INT AUTO_INCREMENT PRIMARY KEY, mahasiswa_id INT NOT NULL, tanggal DATE NOT NULL, phq9 TINYINT NOT NULL, gad7 TINYINT NOT NULL, jam_tidur DECIMAL(3,1) NOT NULL, keluhan VARCHAR(255) NOT NULL, tingkat TINYINT NOT NULL COMMENT '0=Rendah,1=Sedang,2=Tinggi,3=Kritis', FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE) ENGINE=InnoDB;
CREATE TABLE konseling (mahasiswa_id INT PRIMARY KEY, status ENUM('Belum','Terjadwal','Berjalan','Selesai') NOT NULL DEFAULT 'Belum', catatan TEXT, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE) ENGINE=InnoDB;
CREATE VIEW v_terakhir AS SELECT m.*, s.id AS skrining_id, s.tanggal, s.phq9, s.gad7, s.jam_tidur, s.keluhan, s.tingkat, COALESCE(k.status,'Belum') AS konseling, k.catatan FROM mahasiswa m JOIN skrining s ON s.id=(SELECT MAX(id) FROM skrining WHERE mahasiswa_id=m.id) LEFT JOIN konseling k ON k.mahasiswa_id=m.id;

